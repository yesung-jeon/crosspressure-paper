#!/usr/bin/env python
"""Validate a run against the sealed bf16 release.

Two checks, both required:
  1. Every output file: sha256 equal to validation/SEAL.json. This covers every table cell, figure and GPU part file. On the same Linux
     setup a Path B or Path A rerun is bit-identical;.gz files are compared by decompressed content and files listed in VOLATILE (and every
     run.json, fields RUN_TIMES) carry wall-clock times and are compared with those fields removed.
  2. Headline values (tools/headline_values.py): verdicts and counts exactly equal, numbers |diff| <= 1e-9, against
     validation/headline_values.csv. On other hardware or library versions check 1 may fail while check 2 shows the size of the change.
Writes logs/validation.json and exits 0 only if both pass.

Usage: python tools/validate.py            check this tree
       python tools/validate.py --seal     maintainers only: write SEAL.json and headline_values.csv from this tree (the sealed P4 run)"""
import argparse, csv, gzip, hashlib, json, sys
from pathlib import Path

R = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(R / "tools"))
import headline_values as hv  # noqa: E402

VAL = R / "validation"
STUDIES = sorted(p.name for p in R.iterdir() if p.is_dir() and p.name[:2].isdigit() and p.name != "00_shared")
SKIP_DIRS = {"code", "protocol", "__pycache__", "logs"}   # logs/ (e.g. R session info) is not shipped
SKIP_SUFFIX = {".py", ".R", ".rds"}
NOT_SHIPPED = ("12_speech_and_state/out/s0/",)      # regenerated by every run; also in.gitignore
# JSON keys holding wall-clock values, found by the rename gate (2026-10-24, the first full Path B rerun on the P4 outputs): Study M
# RESULTS files write "run" (time of the run). Every other regenerated file was byte-identical, apart from gzip headers (time stamp;
# .gz files are therefore compared by their decompressed content) and .rds model objects (not shipped).
VOLATILE = {f"18_economic_weight/out/{x}": {"run"} for x in ("x1/RESULTS.json", "x2/RESULTS.json",
            "x3/RESULTS.json", "x4/RESULTS.json", "x5/RESULTS_stageA.json", "x5/RESULTS_stageB.json")}
RUN_TIMES = {"finished", "seconds_this_run", "sec_per_prompt"}   # wall-clock fields of every */run.json (06 v4, 09 yesno); found by P6
TOL = 1e-9


def outputs(root):
    """Every output file: under a study folder, not code or protocol, not a MANIFEST file (frozen inputs such as 06/out/v1 live under
    out/ but are inputs, checked by MANIFEST sha256), not regenerated-only material."""
    listed = set(json.load(open(root / "MANIFEST.json", encoding="utf-8"))["files"])
    for s in STUDIES:
        for p in sorted((root / s).rglob("*")):
            rel = p.relative_to(root).as_posix()
            if not p.is_file() or SKIP_DIRS & set(p.relative_to(root / s).parts[:-1]) or p.suffix in SKIP_SUFFIX: continue
            if p.name.endswith("_input.csv.gz") or rel.startswith(NOT_SHIPPED) or rel in listed: continue
            yield rel, p


def digest(rel, p):
    drop = VOLATILE.get(rel) or (RUN_TIMES if p.name == "run.json" else None)
    if drop:
        d = json.load(open(p, encoding="utf-8"))
        def strip(x):
            if isinstance(x, dict): return {k: strip(v) for k, v in x.items() if k not in drop}
            if isinstance(x, list): return [strip(v) for v in x]
            return x
        return "volatile:" + hashlib.sha256(json.dumps(strip(d), sort_keys=True).encode()).hexdigest()
    h = hashlib.sha256()
    with (gzip.open(p, "rb") if p.suffix == ".gz" else open(p, "rb")) as f:
        for b in iter(lambda: f.read(1 << 20), b""): h.update(b)
    return h.hexdigest()


def paper_digests():
    """sha256 of the paper's value files and generated tables (rebuilt by paper/build.py from the sealed headline table)"""
    P = R / "paper"; files = [P / "values.json", P / "appendix_values.json"] + sorted((P / "tables").glob("*.md"))
    return {str(f.relative_to(R)): hashlib.sha256(f.read_bytes()).hexdigest() for f in files if f.is_file()}


def headline_check():
    new = hv.values(R, "new"); old = list(csv.DictReader(open(VAL / "headline_values.csv", encoding="utf-8")))
    key = lambda x: (x["study"], x["model"], x["issue"], x["quantity"])
    o = {key(x): x for x in old}; bad = []
    if len(o) != len(old): raise SystemExit("duplicate headline keys in the sealed table")
    for x in new:
        s = o.pop(key(x), None)
        if s is None: bad.append(dict(row=key(x), problem="not in sealed table")); continue
        if x["verdict"] != s["verdict"]: bad.append(dict(row=key(x), problem="verdict", sealed=s["verdict"], now=x["verdict"]))
        for c in ("estimate", "lower95", "upper95"):
            a, b = x[c], (float(s[c]) if s[c] not in ("", None) else None)
            if (a is None) != (b is None) or (a is not None and abs(a - b) > TOL):
                bad.append(dict(row=key(x), problem=c, sealed=b, now=a))
    bad += [dict(row=k, problem="sealed row not produced") for k in o]
    return len(new), bad


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--seal", action="store_true"); a = ap.parse_args()
    if a.seal:
        VAL.mkdir(exist_ok=True)
        seal = {rel: digest(rel, p) for rel, p in outputs(R)}
        json.dump(dict(rule=__doc__.split("\n")[0], n_files=len(seal), files=seal), open(VAL / "SEAL.json", "w"), indent=0)
        rows = hv.values(R, "new")
        with open(VAL / "headline_values.csv", "w", newline="", encoding="utf-8") as f:
            w = csv.DictWriter(f, fieldnames=list(rows[0])); w.writeheader()
            for x in rows: w.writerow({k: (repr(v) if isinstance(v, float) else v) for k, v in x.items()})
        json.dump(paper_digests(), open(VAL / "PAPER_SEAL.json", "w"), indent=0)
        print(f"sealed {len(seal)} output files and {len(rows)} headline rows (+ paper value files and tables)"); return 0
    seal = json.load(open(VAL / "SEAL.json", encoding="utf-8"))["files"]
    now = dict(outputs(R))
    res = dict(missing=sorted(set(seal) - set(now)), extra=sorted(set(now) - set(seal)), differ=[], identical=0)
    for rel in sorted(set(seal) & set(now)):
        if digest(rel, now[rel]) == seal[rel]: res["identical"] += 1
        else: res["differ"].append(rel)
    n, bad = headline_check()
    res.update(headline_rows=n, headline_problems=bad)
    # MANIFEST inputs (code, protocols, frozen inputs): sha256 as recorded
    man = json.load(open(R / "MANIFEST.json", encoding="utf-8"))["files"]
    res["manifest_bad"] = [k for k, v in man.items()
                           if not (R / k).is_file() or hashlib.sha256((R / k).read_bytes()).hexdigest() != v["sha256"]]
    # paper value files and tables (audit 11-01b I3-3): the numbers the manuscript prints, sealed with the outputs; figures are checked
    # by paper/build.py against figures/FIGURES_SHA256.ref.json (reported, not fatal: other machines' libraries change pixels)
    ps = VAL / "PAPER_SEAL.json"
    if ps.exists():
        old_p, new_p = json.load(open(ps, encoding="utf-8")), paper_digests()
        res["paper_differ"] = sorted(k for k in set(old_p) | set(new_p) if old_p.get(k) != new_p.get(k))
    else:
        res["paper_differ"] = ["(no PAPER_SEAL.json)"]
    res["files_pass"] = (not res["missing"] and not res["differ"] and not res["extra"] and not res["manifest_bad"]
                         and not res["paper_differ"])   # an unsealed output also fails
    res["headline_pass"] = not bad
    res["pass"] = res["files_pass"] and res["headline_pass"]
    (R / "logs").mkdir(exist_ok=True); json.dump(res, open(R / "logs" / "validation.json", "w"), indent=1, default=str)
    print(f"files: {res['identical']} identical, {len(res['differ'])} differ, {len(res['missing'])} missing, {len(res['extra'])} not sealed")
    for rel in res["differ"][:40]: print("  DIFFER", rel)
    for rel in res["missing"][:40]: print("  MISSING", rel)
    print(f"manifest: {len(man)} inputs, {len(res['manifest_bad'])} not matching their recorded sha256")
    print(f"paper value files and tables: {len(res['paper_differ'])} differ from PAPER_SEAL.json")
    for rel in res["paper_differ"][:20]: print("  PAPER", rel)
    for rel in res["manifest_bad"][:40]: print("  MANIFEST", rel)
    print(f"headline values: {n} rows, {len(bad)} problems")
    for b in bad[:40]: print("  ", b)
    print("PASS" if res["pass"] else "FAIL")
    return 0 if res["pass"] else 1


if __name__ == "__main__":
    sys.exit(main())
