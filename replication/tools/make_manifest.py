#!/usr/bin/env python
"""Package manifest (rebuild PLAN v0.2 §9.1-1(a), Rhee replication-package rules): the files a clean Path A run starts from = code,
configuration, protocols and frozen inputs; never model outputs or analysis outputs. MANIFEST.json lists each file with its sha256 and
role. --copy <dir> copies exactly these files (plus ../congress_map and ../data_generation) into a new directory for a clean run.
  python make_manifest.py            -> MANIFEST.json
  python make_manifest.py --copy D   -> D/replication, D/congress_map, D/data_generation (raw data are fetched by the run)"""
import hashlib, json, shutil, sys
from pathlib import Path

R = Path(__file__).resolve().parents[1]                 # replication/ (this file is in tools/)
CODE_EXT = {".py", ".R", ".sh", ".md", ".txt"}
# Frozen inputs: cannot be regenerated by a script (author judgments, LLM-written or LLM-checked text, hand-coded material) or fixed by
# design (the A12 selection). Each is listed by path; anything else under an out/ folder is an output and is not in the manifest.
FROZEN = [
    "02_ideology_map/out/s4b/selection.csv", "02_ideology_map/out/s4b/coding_sheet.csv", "02_ideology_map/out/s4b/coding_codes.csv",
    "02_ideology_map/out/s4b/coding_codes.sha256", "02_ideology_map/out/s4b/wiki_ledger.csv",
    "02_ideology_map/out/s4c/selection.csv", "02_ideology_map/out/s4c/coding_sheet.csv", "02_ideology_map/out/s4c/coding_codes.csv",
    "02_ideology_map/out/s4c/coding_codes.sha256", "02_ideology_map/out/s4c/wiki_ledger.csv",
    "06_vote_prediction/out/v1/**", "06_vote_prediction/out/v2/**",
    "06_vote_prediction/out/g2/AUTHOR_DESC_CHECK.csv", "06_vote_prediction/out/g2/author_desc_view.txt", "06_vote_prediction/out/g2/PRE_RUN_SEAL.json",
    "06_vote_prediction/out/g2/verify.csv", "06_vote_prediction/out/g2/verify_round1.csv", "06_vote_prediction/out/g2/verify_round2.csv",
    "06_vote_prediction/out/g2/verify_summary.json", "06_vote_prediction/out/g2/verify_ledger/**",
    "05_gun_scale/out/g0/AUTHOR_REVIEW.csv", "05_gun_scale/out/g0/labels_merged.csv", "05_gun_scale/out/g0/labels_gpt.csv",
    "05_gun_scale/out/g0/gpt_log.txt", "05_gun_scale/out/g0/contested_texts.csv", "05_gun_scale/out/g0/gpt_ledger/**",
    "01_rollcall_scales/out/speech/link_bound.csv", "01_rollcall_scales/out/speech/link_daily.csv",
    "06_vote_prediction/protocol/prompts_content_sha256.json", "06_vote_prediction/protocol/prompts_fixed_sha256.json",
]
SKIP_DIRS = {"out", "out_layercheck", "logs", "__pycache__", "legacy_fp8_2026-10-19", "values", "data_fake",
             "results", "results_fake", "data", "models", "tables", "figures"}


def sha(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()


def frozen_files():
    out = []
    for pat in FROZEN:
        if pat.endswith("/**"): out += [p for p in (R / pat[:-3]).rglob("*") if p.is_file()]
        else: out.append(R / pat)
    missing = [str(p) for p in out if not p.exists()]
    assert not missing, f"frozen inputs missing: {missing}"
    return out


def code_files():
    out = []
    for p in R.rglob("*"):
        if not p.is_file(): continue
        rel = p.relative_to(R)
        if any(part in SKIP_DIRS for part in rel.parts[:-1]): continue
        if p.suffix in CODE_EXT or p.parent.name in ("config", "protocol") or p.name in ("items_j.json", "items_j.sha256", "overrides.json", "NAME_MAP.csv", "LICENSE", "LICENSE-DATA") \
                or (p.suffix == ".json" and p.name.startswith(("PROTOCOL_SEAL", "PROTOCOL"))) or rel.parts[0] == "01_rollcall_scales" and "issue_data" in rel.parts:
            out.append(p)
    data_code = [R / "data" / "fetch_data.py"]
    return out + data_code


files = sorted(set(code_files()) | set(frozen_files()))
FRZ = set(frozen_files())
man = {"rule": "code, configuration, protocols and frozen inputs; no outputs", "files": {
    str(p.relative_to(R)): {"sha256": sha(p), "bytes": p.stat().st_size, "role": "frozen input" if p in FRZ else "code/config/doc"} for p in files}}
if "--copy" in sys.argv:
    dst = Path(sys.argv[sys.argv.index("--copy") + 1]).resolve(); assert not dst.exists(), f"{dst} exists: use a new directory"
    for rel in man["files"]:
        t = dst / "replication" / rel; t.parent.mkdir(parents=True, exist_ok=True); shutil.copy2(R / rel, t)
    for sib in ("congress_map", "data_generation"):
        shutil.copytree(R.parent / sib, dst / sib, ignore=shutil.ignore_patterns("__pycache__"))
    print("copied", len(man["files"]), "package files to", dst)
else:
    json.dump(man, open(R / "MANIFEST.json", "w"), indent=1)
    n_f = sum(v["role"] == "frozen input" for v in man["files"].values())
    print("MANIFEST.json:", len(man["files"]), "files,", n_f, "frozen inputs,", sum(v["bytes"] for v in man["files"].values()) // 2**20, "MB")
